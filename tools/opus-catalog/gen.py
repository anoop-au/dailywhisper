#!/usr/bin/env python3
"""Regenerates app/src/main/java/com/anoop/dailywhisper/OpusMtCatalog.kt from the Hugging Face API.
Each Xenova/opus-mt-<src>-<tgt> repo (or the REPOS override) is pinned to its current commit; every file gets its size and SHA-256
(LFS files from the API, small JSON files by downloading them at that commit). Run: tools/opus-catalog/gen.py"""
import json, hashlib, urllib.request, concurrent.futures as cf, os
# One-to-one models only (multilingual ones need extra target tags). no-de left out: tiny 7k vocab model.
PAIRS = """af-en ar-en cs-en da-de da-en de-en de-es de-fr en-af en-ar en-cs en-da en-de en-es en-fi en-fr en-hi en-hu
en-id en-it en-nl en-ro en-ru en-sv en-uk en-vi en-zh es-de es-en es-fr es-it es-ru et-en fi-de fi-en fr-de fr-en fr-es
fr-ro fr-ru hi-en hu-en id-en it-en it-es it-fr ja-en ko-en nl-en nl-fr pl-en ro-fr ru-en ru-es ru-fr ru-uk sv-en th-en
tr-en uk-en uk-ru vi-en zh-en en-ml ml-en""".split()
# Pairs Xenova doesn't publish: our own int8 ONNX exports of Helsinki-NLP/opus-mt-<pair> (same file layout), made with
# the Xenova conversion steps and hosted publicly on Hugging Face (see each repo's model card).
REPOS = {"en-ml": "akm9191/opus-mt-en-ml-int8-onnx", "ml-en": "akm9191/opus-mt-ml-en-int8-onnx"}
FILES = [("onnx/encoder_model_quantized.onnx", "encoder.onnx"), ("onnx/decoder_model_merged_quantized.onnx", "decoder.onnx"),
         ("tokenizer.json", "tokenizer.json"), ("config.json", "config.json")]
def get(u): return json.load(urllib.request.urlopen(u))
def one(p):
    repo = REPOS.get(p, f"Xenova/opus-mt-{p}")
    sha = get(f"https://huggingface.co/api/models/{repo}")["sha"]
    tree = {}
    for d in ("", "onnx"):
        for f in get(f"https://huggingface.co/api/models/{repo}/tree/{sha}/{d}"):
            tree[f["path"]] = f
    out = []
    for src, local in FILES:
        f = tree[src]
        if f.get("lfs"):
            size, digest = f["lfs"]["size"], f["lfs"]["oid"]
        else:
            b = urllib.request.urlopen(f"https://huggingface.co/{repo}/resolve/{sha}/{src}").read()
            assert len(b) == f["size"]
            size, digest = len(b), hashlib.sha256(b).hexdigest()
        out.append((src, local, size, digest))
    return p, repo, sha, out
with cf.ThreadPoolExecutor(12) as ex:
    rows = sorted(ex.map(one, PAIRS))
L = ["package com.anoop.dailywhisper", "",
     "// GENERATED by tools/opus-catalog/gen.py. Do not edit by hand.",
     "// Helsinki-NLP Opus-MT (MarianMT, Apache-2.0 per the model cards) as ONNX exports in the Xenova/opus-mt-* repos on",
     "// Hugging Face (Malayalam: our own exports, same layout, in akm9191/opus-mt-*-int8-onnx), each pinned to a commit.",
     "// Files: int8 encoder, int8 merged decoder (with KV cache), tokenizer, config.",
     "object OpusMtCatalog {",
     "    class File(val path: String, val local: String, val size: Long, val sha256: String)",
     "    class Model(val pair: String, val revision: String, val files: List<File>, val repo: String) {",
     "        val bytes get() = files.sumOf { it.size }",
     "        fun url(f: File) = \"https://huggingface.co/$repo/resolve/$revision/${f.path}\"",
     "    }",
     "    private fun m(pair: String, rev: String, vararg f: File, repo: String = \"Xenova/opus-mt-$pair\") = Model(pair, rev, f.toList(), repo)",
     "    private fun f(path: String, local: String, size: Long, sha: String) = File(path, local, size, sha)",
     "    val MODELS: Map<String, Model> = listOf("]
for p, repo, sha, files in rows:
    L.append(f'        m("{p}", "{sha}",')
    for src, local, size, d in files:
        L.append(f'            f("{src}", "{local}", {size}L, "{d}"),')
    L.append(f'            repo = "{repo}",' if repo in REPOS.values() else "")
    L[-1] or L.pop()
    L.append("        ),")
L += ["    ).associateBy { it.pair }", "}", ""]
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../app/src/main/java/com/anoop/dailywhisper/OpusMtCatalog.kt")
open(dst, "w").write("\n".join(L))
print(len(rows), "models ->", os.path.normpath(dst))
